// ---- 資金繰り（キャッシュコンバージョン）----
export interface CashInput {
  amountJPY: number;           // 仕入れ総額（円）
  marginRate: number;          // 粗利率（%）
  producerTerm: number;        // 生産者への支払い（B/L日を0日として、前＝マイナス、後＝プラス）。例：発注時に前払い=-30、出荷後30日払い=+30
  buyerTerm: number;           // バイヤーからの入金日（B/L日を0日として）。前払い=-14、L/C=+10、D/A60=+60、O/A90=+90
  financeRate: number;         // 資金調達コスト（年率%）
}
export function cashCycle(i: CashInput) {
  const sales = i.amountJPY / (1 - i.marginRate / 100);
  const gap = i.buyerTerm - i.producerTerm; // 正＝自社が立て替える日数
  const cost = Math.round(i.amountJPY * (i.financeRate / 100) * (Math.max(gap, 0) / 365));
  const peak = gap > 0 ? i.amountJPY : 0; // 立て替えが必要な最大額（簡易）
  return { gapDays: gap, salesJPY: Math.round(sales), profitJPY: Math.round(sales - i.amountJPY), financeCostJPY: cost, netProfitJPY: Math.round(sales - i.amountJPY - cost), peakFundingJPY: Math.round(peak), financedByBuyer: gap < 0 };
}
